  /** 角度の表を守っているか。pick を渡すと差し替えた読みで試せる(反証用) */
  function seiyouAngleProblems(yomiOf) {
    var problems = [], f, i, k;
    var pick = yomiOf || seiyouYomiOf;
    var fields = [], label;
    for (label in SEIYOU_ANGLE) { if (own(SEIYOU_ANGLE, label)) { fields.push(label); } }
    for (f = 0; f < fields.length; f++) {
      var angle = SEIYOU_ANGLE[fields[f]];
      var keys = seiyouYomiKeys(fields[f]);
      for (i = 0; i < keys.length; i++) {
        var text = pick(fields[f], keys[i]);
        if (text === null || text === undefined) { continue; }
        var at = fields[f] + '/' + keys[i];
        var hit = false;
        for (k = 0; k < angle.must.length; k++) {
          if (text.indexOf(angle.must[k]) >= 0) { hit = true; }
        }
        if (!hit) {
          problems.push(at + ': この欄の角度(' + angle.desc + ')の言い回しが1つも無い');
        }
        for (k = 0; k < angle.avoid.length; k++) {
          if (text.indexOf(angle.avoid[k]) >= 0) {
            problems.push(at + ': 別の欄の角度の語「' + angle.avoid[k] + '」が入っている');
          }
        }
      }
    }
    return problems;
  }

  /** 「逆に」の文(=向かない場面を述べるところ)が含みのある言い方で結んでいるか。
      向かない場面は断定がいちばん出てはいけない位置なのに、言い切りの一覧
      (KANSHI_ASSERT)では捕まらない(cycle-0085 の点検役 M2) */
  function seiyouHedgeProblems(yomiOf) {
    var problems = [], i, j;
    var pick = yomiOf || seiyouYomiOf;
    var texts = seiyouYomiTexts();
    var hedge = official.util.kanshiHedge;
    for (i = 0; i < texts.length; i++) {
      var parts = texts[i].at.split('/');
      var text = pick(parts[0], parts[1]);
      if (text === null || text === undefined) { continue; }
      var ss = official.util.kanshiSentencesOf(text);
      var found = 0;
      for (j = 0; j < ss.length; j++) {
        if (ss[j].indexOf('逆に') < 0) { continue; }
        found++;
        if (!hedge.test(ss[j])) {
          problems.push(texts[i].at + ': 「逆に」の文が含みのある言い方で結んでいない「' + ss[j] + '」');
        }
      }
      if (found === 0) { problems.push(texts[i].at + ': 「逆に」で切り返す文が無い'); }
    }
    return problems;
  }

