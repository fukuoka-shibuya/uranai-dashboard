  /** 角度の表を守っているか。pick を渡すと差し替えた読みで試せる(反証用) */
  function shukuAngleProblems(yomiOf) {
    var problems = [], f, i, k;
    var pick = yomiOf || shukuYomiOf;
    var fields = shukuYomiFields();
    for (f = 0; f < fields.length; f++) {
      var angle = SHUKU_ANGLE[fields[f]];
      var keys = shukuYomiKeys(fields[f]);
      for (i = 0; i < keys.length; i++) {
        var text = pick(fields[f], keys[i]);
        if (text === null || text === undefined) { continue; }
        var at = fields[f] + '/' + keys[i];
        var hit = false;
        for (k = 0; k < angle.must.length; k++) {
          if (text.indexOf(angle.must[k]) >= 0) { hit = true; }
        }
        if (!hit) {
          problems.push(at + ': この欄の角度(' + angle.desc + ')の言い回しが1つも無い');
        }
        for (k = 0; k < angle.avoid.length; k++) {
          if (text.indexOf(angle.avoid[k]) >= 0) {
            problems.push(at + ': 別の欄の角度の語「' + angle.avoid[k] + '」が入っている');
          }
        }
      }
    }
    return problems;
  }

  /** 同じ画面に並ぶ2欄の重なり。**画面に実際に出ている note を読む**ので、
      表へ入れただけで画面につながっていない文は数に入らない。宿は旧暦の日で
      決まるので、連続した日付を送れば27通りの画面がすべて現れる */
  function shukuScreens() {
    var out = [], seen = {}, d, i;
    for (d = 0; d < 400 && out.length < 27; d++) {
      var bd = new Date(Date.UTC(2000, 0, 1 + d)).toISOString().slice(0, 10);
      var r = computeOne('sukuyo', { birthdate: bd });
      if (!r || !r.items) { continue; }
      var shuku = '', texts = [];
      for (i = 0; i < r.items.length; i++) {
        if (r.items[i].label === '生まれの宿') { shuku = r.items[i].value; }
        texts.push({ at: r.items[i].label + '/' + r.items[i].value,
                     text: r.items[i].note || '' });
      }
      if (shuku && !own(seen, shuku)) {
        seen[shuku] = true;
        out.push({ shuku: shuku, texts: texts });
      }
    }
    return out;
  }

  function shukuSameScreenOverlap() {
    var screens = shukuScreens(), i;
    if (screens.length === 0) {
      return { measured: false, count: 0, average: null, max: null, worst: '',
               limits: official.util.kanshiSameKeyLimits };
    }
    var sum = 0, max = 0, worst = '';
    for (i = 0; i < screens.length; i++) {
      var one = official.util.kanshiPairOverlapOf(screens[i].texts);
      sum += (one.average === null) ? 0 : one.average;
      if (one.max > max) { max = one.max; worst = screens[i].shuku + ' の画面(' + one.worst + ')'; }
    }
    return { measured: true, count: screens.length, average: sum / screens.length,
             max: max, worst: worst, limits: official.util.kanshiSameKeyLimits };
  }

